/**
 * Translate any UI key across all 19 locales, falling back cleanly through:
 * 1. Explicit UI locale overrides (EXTRA_LOCALES)
 * 2. Extracted ani.pm locale bundle namespaces (nav, common, browse, animeDetails, auth, search)
 * 3. English US baseline
 */
export function translate(
  locale: LocaleTag,
  key: string,
  params?: Record<string, string | number>
): string {
  let raw = EXTRA_LOCALES[locale]?.[key];

  if (!raw && locale !== DEFAULT_LOCALE) {
    const locBundle = extracted[locale];
    if (locBundle) {
      // Map common keys to extracted ani.pm namespace keys
      const aliasMap: Record<string, [string, string]> = {
        'nav.home': ['nav', 'dest.home'],
        'nav.browse': ['nav', 'dest.browse'],
        'nav.latest': ['nav', 'dest.latest'],
        'nav.genres': ['nav', 'dest.genres'],
        'nav.library': ['nav', 'dest.library'],
        'nav.settings': ['nav', 'dest.settings'],
        'nav.leaderboard': ['nav', 'dest.leaderboard'],
        'home.viewAll': ['common', 'action.showMore'],
        'detail.watchNow': ['animeDetails', 'action.watchNow'],
        'detail.episodes': ['animeDetails', 'tab.episodes'],
        'detail.related': ['animeDetails', 'tab.related'],
        'detail.comments': ['common', 'label.comments'],
        'nav.signIn': ['auth', 'action.signIn'],
      };
      const mapped = aliasMap[key];
      if (mapped) {
        raw = locBundle[mapped[0]]?.[mapped[1]];
      }
      if (!raw) {
        for (const ns of Object.values(locBundle)) {
          if (typeof ns[key] === 'string') {
            raw = ns[key];
            break;
          }
        }
      }
    }
  }

  const template = raw ?? UI_STRINGS_EN[key] ?? key;
  if (!params) return template;

  return template.replace(/\{(\w+)\}/g, (_, k) =>
    params[k] !== undefined ? String(params[k]) : `{${k}}`
  );
}
